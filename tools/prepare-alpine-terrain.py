"""Prepare the local alpine height field from public Mapzen Terrarium tiles.

Run with Python + Pillow + NumPy. Network is used only by this offline tool;
the website ships its own compact terrain module. Attribution: docs/autumn-assets.md.
"""
import base64
import json
import math
from pathlib import Path
from urllib.request import urlopen

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'artifacts' / 'terrain-source'
CACHE.mkdir(parents=True, exist_ok=True)
ZOOM = 13
COLUMNS, ROWS = 385, 257
NEAR_LON, NEAR_LAT = 7.726, 46.503
HEADING = math.radians(104)
WIDTH_METRES, DEPTH_METRES = 11000, 8000

def pixel(lon, lat):
    n = (2 ** ZOOM) * 256
    return ((lon + 180) / 360 * n,
            (1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n)

# Look from the lake basin toward the massif, instead of over an intervening
# northern ridge. A rotated geographic crop retains the actual glacial walls.
across, along = np.meshgrid(np.linspace(-WIDTH_METRES/2, WIDTH_METRES/2, COLUMNS),
                           np.linspace(DEPTH_METRES, 0, ROWS))
east = math.sin(HEADING)*along + math.cos(HEADING)*across
north = math.cos(HEADING)*along - math.sin(HEADING)*across
lon = NEAR_LON + east / (111320*math.cos(math.radians(NEAR_LAT)))
lat = NEAR_LAT + north / 111320
WEST,SOUTH,EAST,NORTH = float(lon.min()),float(lat.min()),float(lon.max()),float(lat.max())
left, top = pixel(WEST, NORTH)
right, bottom = pixel(EAST, SOUTH)
tx0, ty0, tx1, ty1 = math.floor(left / 256), math.floor(top / 256), math.floor(right / 256), math.floor(bottom / 256)
mosaic = np.zeros(((ty1 - ty0 + 1) * 256, (tx1 - tx0 + 1) * 256), dtype=np.float64)
sources = []
for ty in range(ty0, ty1 + 1):
    for tx in range(tx0, tx1 + 1):
        url = f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{ZOOM}/{tx}/{ty}.png'
        file = CACHE / f'{ZOOM}-{tx}-{ty}.png'
        if not file.exists():
            with urlopen(url, timeout=30) as response:
                file.write_bytes(response.read())
        rgb = np.asarray(Image.open(file).convert('RGB'), dtype=np.float64)
        elevation = rgb[:, :, 0] * 256 + rgb[:, :, 1] + rgb[:, :, 2] / 256 - 32768
        assert np.isfinite(elevation).all() and elevation.min() > 0 and elevation.max() < 5000
        mosaic[(ty-ty0)*256:(ty-ty0+1)*256, (tx-tx0)*256:(tx-tx0+1)*256] = elevation
        sources.append(url)

# Sample the same rotated grid. Rows increase from the far ridge to the lake.
size = (2**ZOOM)*256
x = (lon+180)/360*size - tx0*256
y = (1-np.arcsinh(np.tan(np.radians(lat)))/math.pi)/2*size - ty0*256
ix, iy = np.floor(x).astype(int), np.floor(y).astype(int)
u, v = x - ix, y - iy
height = ((1-v) * ((1-u)*mosaic[iy, ix] + u*mosaic[iy, ix+1])
          + v * ((1-u)*mosaic[iy+1, ix] + u*mosaic[iy+1, ix+1]))
# Decimetre quantization stays well below the source DEM resolution.
encoded = np.rint(height * 10).astype('<u2')
payload = base64.b64encode(encoded.tobytes()).decode('ascii')
module = '''// Generated by tools/prepare-alpine-terrain.py. Do not edit by hand.
// Swiss alpine DEM, cropped/rotated for an artistic scene; not navigational data.
// Produced using Copernicus data and information funded by the EU (EU-DEM).
// SRTM data courtesy of USGS; assembled as Mapzen Terrain Tiles on AWS.
// Full provenance and attribution: docs/autumn-assets.md.
export const terrainColumns = %d;
export const terrainRows = %d;
const bytes = Uint8Array.from(atob('%s'), c => c.charCodeAt(0));
const view = new DataView(bytes.buffer);
export const alpineElevations = Float32Array.from({ length: %d }, (_, i) => view.getUint16(i * 2, true) / 10);
''' % (COLUMNS, ROWS, payload, COLUMNS * ROWS)
(ROOT / 'src' / 'autumn' / 'alpine-elevation.js').write_text(module, encoding='utf-8')
(CACHE / 'provenance.json').write_text(json.dumps({'zoom': ZOOM, 'bounds': [WEST,SOUTH,EAST,NORTH], 'nearCentre': [NEAR_LON,NEAR_LAT], 'heading':math.degrees(HEADING), 'widthMetres':WIDTH_METRES, 'depthMetres':DEPTH_METRES, 'columns': COLUMNS, 'rows': ROWS, 'tiles': sources}, indent=2))
print(json.dumps({'min': float(height.min()), 'max': float(height.max()), 'peak': list(map(int,np.unravel_index(height.argmax(),height.shape))), 'tiles':len(sources), 'moduleBytes':len(module)}))
