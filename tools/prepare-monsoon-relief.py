"""Sample the CC0 Poly Haven Rock Face displacement scan for live terrain relief.

Input: artifacts/rock_face_disp_1k.png, fetched from the Poly Haven files API.
The reduced scalar field is data for geometry, not a displayed image.
"""
import base64
from pathlib import Path
import numpy as np
from PIL import Image

root=Path(__file__).resolve().parents[1]
source=np.asarray(Image.open(root/'artifacts/rock_face_disp_1k.png'),dtype=np.float64)
if source.ndim==3:
    source=source[:,:,0]
sample=source[::8,::8]
sample=(sample-sample.min())/(sample.max()-sample.min())
payload=base64.b64encode(np.rint(sample*255).astype('uint8').tobytes()).decode('ascii')
(root/'src/monsoon/rock-relief.js').write_text(f'''// Reduced Poly Haven Rock Face displacement scan, CC0.
// Generated by tools/prepare-monsoon-relief.py. Source: https://polyhaven.com/a/rock_face
const values=Uint8Array.from(atob('{payload}'),c=>c.charCodeAt(0));
const size={sample.shape[0]};
export function rockRelief(x,z) {{
  const u=(x-Math.floor(x))*(size-1),v=(z-Math.floor(z))*(size-1);
  const a=Math.floor(u),b=Math.floor(v),tx=u-a,tz=v-b;
  const at=(dx,dz)=>values[((b+dz)%size)*size+(a+dx)%size]/255;
  return (at(0,0)*(1-tx)+at(1,0)*tx)*(1-tz)+(at(0,1)*(1-tx)+at(1,1)*tx)*tz;
}}
''',encoding='utf-8')
print('Bundled',sample.size,'relief samples')
