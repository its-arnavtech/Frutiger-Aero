"""Bundle a north-facing Matterhorn DEM crop for Rainmere. Not navigational data.

Public Mapzen Terrarium source; credits in docs/monsoon-assets.md.
Run with Python, NumPy and Pillow. Tiles are cached only in ignored artifacts/.
"""
import base64
import json
import math
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.request import urlopen

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'artifacts' / 'monsoon-dem'
CACHE.mkdir(parents=True, exist_ok=True)
ZOOM, COLUMNS, ROWS = 14, 513, 385
LON, LAT = 7.6586, 45.9763
WEST_X, EAST_X, FAR_Z, NEAR_Z = -800, 800, -1600, -440
# Six source metres per world metre; summit aligns with the existing subject.
x, z = np.meshgrid(np.linspace(WEST_X, EAST_X, COLUMNS), np.linspace(FAR_Z, NEAR_Z, ROWS))
lon = LON + (x + 24) * 6 / (111320 * math.cos(math.radians(LAT)))
lat = LAT + (z + 890) * 6 / 111320
size = 2 ** ZOOM * 256
px = (lon + 180) / 360 * size
py = (1 - np.arcsinh(np.tan(np.radians(lat))) / math.pi) / 2 * size
tx0, tx1 = math.floor(px.min()/256), math.floor(px.max()/256)
ty0, ty1 = math.floor(py.min()/256), math.floor(py.max()/256)
tiles = [(tx,ty) for ty in range(ty0,ty1+1) for tx in range(tx0,tx1+1)]

def tile(pair):
    tx,ty = pair
    url = f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{ZOOM}/{tx}/{ty}.png'
    file = CACHE / f'{ZOOM}-{tx}-{ty}.png'
    if not file.exists():
        with urlopen(url,timeout=45) as response:
            file.write_bytes(response.read())
    rgb=np.asarray(Image.open(file).convert('RGB'),dtype=np.float64)
    return tx,ty,rgb[:,:,0]*256+rgb[:,:,1]+rgb[:,:,2]/256-32768,url

mosaic=np.zeros(((ty1-ty0+1)*256,(tx1-tx0+1)*256),dtype=np.float64)
sources=[]
with ThreadPoolExecutor(max_workers=6) as pool:
    for tx,ty,height,url in pool.map(tile,tiles):
        mosaic[(ty-ty0)*256:(ty-ty0+1)*256,(tx-tx0)*256:(tx-tx0+1)*256]=height
        sources.append(url)
px-=tx0*256; py-=ty0*256
ix,iy=np.floor(px).astype(int),np.floor(py).astype(int)
u,v=px-ix,py-iy
height=(1-v)*((1-u)*mosaic[iy,ix]+u*mosaic[iy,ix+1])+v*((1-u)*mosaic[iy+1,ix]+u*mosaic[iy+1,ix+1])
assert height.min()>1000 and height.max()<5000
payload=base64.b64encode(np.rint(height*10).astype('<u2').tobytes()).decode('ascii')
module=f'''// Generated by tools/prepare-monsoon-terrain.py from Mapzen Terrain Tiles.
// Produced using Copernicus data and information funded by the EU (EU-DEM).
// SRTM data courtesy of USGS. Full source credits: docs/monsoon-assets.md.
// Scaled artistic terrain, not navigational data.
export const terrainColumns={COLUMNS}, terrainRows={ROWS};
const bytes=Uint8Array.from(atob('{payload}'),c=>c.charCodeAt(0));
const view=new DataView(bytes.buffer);
export const alpineElevations=Float32Array.from({{length:{COLUMNS*ROWS}}},(_,i)=>view.getUint16(i*2,true)/10);
'''
(ROOT/'src/monsoon/alpine-elevation.js').write_text(module,encoding='utf-8')
(CACHE/'provenance.json').write_text(json.dumps({'bounds':[float(lon.min()),float(lat.min()),float(lon.max()),float(lat.max())],'zoom':ZOOM,'tiles':sources,'summit':[LON,LAT]},indent=2))
print(json.dumps({'tiles':len(tiles),'min':float(height.min()),'max':float(height.max()),'moduleBytes':len(module)}))
